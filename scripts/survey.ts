// npm run survey — read-only mainnet survey of a watchlist. Writes data/survey.json (the website's
// trust table) and docs/STATE_OF_NEAR.md. No keys. Neutral language; every row links to evidence.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { inspect, type KeyholeReport } from "../packages/core/src/index.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const watchlist: string[] = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts/data/watchlist.json"), "utf8")).accounts;
const only = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const list = only.length ? only : watchlist;

async function pool<I, O>(items: I[], n: number, fn: (i: I) => Promise<O>): Promise<O[]> {
  const out: O[] = new Array(items.length);
  let next = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (next < items.length) { const i = next++; out[i] = await fn(items[i]); } }));
  return out;
}

export interface SurveyRow {
  account: string;
  verdict: string;
  class: string;
  flags: string[];
  headline: string;
  codeHash: string | null;
  codeSource: string | null;
  fullAccessKeys: number;
  controller: string; // short neutral description of the weakest path
  sourcescan: string | null;
  nep330: "build_info" | "metadata" | "none" | null;
  lastChange: { status: string; height?: number; date?: string; sinceDate?: string } | null;
  explorer: string;
  recheck: string;
}

function controllerText(r: KeyholeReport): string {
  if (!r.code) return "no code";
  if (!r.paths.length) return "nobody (no keys, no deploy capability)";
  const parts: string[] = [];
  if (r.keys.fullAccess.length) parts.push(`${r.keys.fullAccess.length} full-access key${r.keys.fullAccess.length > 1 ? "s" : ""} on the account`);
  for (const o of r.owners.filter((o) => o.actor)) {
    const a = o.actor!;
    if (a.dao?.requiredApprovals != null) parts.push(`DAO ${o.account}: ${a.dao.requiredApprovals} of ${a.dao.roleSize}`);
    else if (a.multisig) parts.push(`multisig ${o.account}: ${a.multisig.required ?? "?"} of ${a.multisig.members ?? "?"}`);
    else if (a.fullAccessKeys) parts.push(`${o.account} (${a.fullAccessKeys} full-access key${a.fullAccessKeys > 1 ? "s" : ""})`);
    else parts.push(`${o.account} (${a.singleKey === null ? "unresolved" : a.summary})`);
  }
  if (r.globalPublisher) parts.push(`global publisher ${r.globalPublisher.account}`);
  if (!parts.length) parts.push(r.paths.map((p) => (p.methods?.length ? `method ${p.methods.join("/")}, owner not found` : "deploy capability, no method found")).join("; "));
  return parts.join("; ");
}

const started = new Date();
const reports = await pool(list, 1, async (account) => {
  try {
    const r = await inspect(account, { network: "mainnet" });
    process.stderr.write(`  ${r.grade.verdict.padEnd(7)} ${r.grade.class.padEnd(10)} ${account}\n`);
    return r;
  } catch (e) {
    process.stderr.write(`  ERROR   ${account}: ${(e as Error).message}\n`);
    return null;
  }
});

const rows: SurveyRow[] = reports.filter((r): r is KeyholeReport => Boolean(r)).map((r) => ({
  account: r.account,
  verdict: r.grade.verdict,
  class: r.grade.class,
  flags: r.grade.flags,
  headline: r.grade.headline,
  codeHash: r.code?.hash ?? null,
  codeSource: r.code?.source ?? null,
  fullAccessKeys: r.keys.fullAccess.length,
  controller: controllerText(r),
  sourcescan: r.sourcescan?.status ?? null,
  nep330: r.nep330 ? (r.nep330.hasBuildInfo ? "build_info" : r.nep330.present ? "metadata" : "none") : null,
  lastChange: r.lastChange ? { status: r.lastChange.status, height: r.lastChange.height, date: r.lastChange.timestamp?.slice(0, 10), sinceDate: r.lastChange.sinceTimestamp?.slice(0, 10) } : null,
  explorer: `https://nearblocks.io/address/${r.account}`,
  recheck: `npx keyhole inspect ${r.account} --evidence`,
}));

const atBlock = Math.max(...reports.filter(Boolean).map((r) => r!.at.height));
fs.mkdirSync(path.join(ROOT, "data"), { recursive: true });
if (!only.length) {
  fs.writeFileSync(path.join(ROOT, "data/survey.json"), JSON.stringify({ schema: "keyhole.survey/1", generatedAt: started.toISOString(), atBlock, network: "mainnet", rows }, null, 1));
}

const count = (f: (r: SurveyRow) => boolean) => rows.filter(f).length;
const md: string[] = [];
md.push(`# State of NEAR contract trust (${started.toISOString().slice(0, 10)})`, "");
md.push(`Generated by \`npm run survey\` at ${started.toISOString().slice(0, 16).replace("T", " ")} UTC, mainnet final block ~${atBlock.toLocaleString("en-US")}. Read-only public RPC. Re-run it to refresh; every row can be re-checked with \`npx keyhole inspect <account> --evidence\`.`, "");
md.push("This table describes trust assumptions (who can change the code, and whether the running code is source-verified). It is not a security audit and does not judge the teams behind these contracts. Owner resolution is inferred from the contracts' own view methods.", "");
md.push(`## Summary (${rows.length} contracts)`, "");
for (const c of ["IMMUTABLE", "GOVERNED", "CUSTODIAL", "UNRESOLVED", "NO_CODE"]) md.push(`- ${c}: ${count((r) => r.class === c)}`);
md.push(`- Current code verified on SourceScan: ${count((r) => r.sourcescan === "verified")}; verified at an older hash only: ${count((r) => r.sourcescan === "stale")}; never verified: ${count((r) => r.sourcescan === "none")}`);
md.push(`- Publish NEP-330 build_info (reproducible-build metadata): ${count((r) => r.nep330 === "build_info")}; NEP-330 without build_info: ${count((r) => r.nep330 === "metadata")}; no NEP-330: ${count((r) => r.nep330 === "none")}`);
md.push(`- Full-access keys on the contract account itself: ${count((r) => r.fullAccessKeys > 0)}`, "");
md.push("## Table", "");
md.push("| Contract | Verdict | Who can change the code (weakest path) | Source verification | NEP-330 | Last code change |");
md.push("|---|---|---|---|---|---|");
for (const r of rows) {
  const lc = r.lastChange?.status === "found" ? `${r.lastChange.date} (block ${r.lastChange.height})` : r.lastChange?.status === "unchanged-since" ? `before ${r.lastChange.sinceDate}` : "unknown";
  md.push(`| [${r.account.length > 28 ? r.account.slice(0, 12) + "…" + r.account.slice(-6) : r.account}](${r.explorer}) | ${r.verdict} · ${r.class} | ${r.controller} | ${r.sourcescan ?? "-"} | ${r.nep330 ?? "-"} | ${lc} |`);
}
md.push("", "Verdicts follow [GRADING.md](GRADING.md): OK requires IMMUTABLE or GOVERNED control *and* source-verified current code. CAUTION is not an accusation; it says a user is trusting something they cannot check from the chain alone.");
if (!only.length) fs.writeFileSync(path.join(ROOT, "docs/STATE_OF_NEAR.md"), md.join("\n") + "\n");
console.log(md.join("\n"));
